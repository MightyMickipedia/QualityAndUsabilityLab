#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Generate German news summaries with the models used for the Konvens study.

This is a cleaned, consolidated version of the original generation scripts.
It uses Ollama for local models and writes generated summaries to a wide CSV.

Expected input CSV columns:
  id or item_id, title, article

Default output columns:
  sauerkraut, mistral-nemo, wiedervereinigung, llama-3b

Run example:
  python generate_summaries.py --input articles.csv --output generated_summaries.csv
  python generate_summaries.py --models sauerkraut mistral-nemo

Notes:
  - gpt3.5 summaries were treated as a baseline in the original working data and
    are not generated by this Ollama script.
  - Decoding is deterministic: temperature=0, top_p=1, num_predict=512.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import shutil
from pathlib import Path
from textwrap import shorten
from typing import Dict, Iterable, List

import pandas as pd
import requests


MODEL_MAP: Dict[str, str] = {
    "sauerkraut": "cyberwald/sauerkrautlm-nemo-12b-instruct",
    "mistral-nemo": "bengt0/em_german_leo_mistral",
    "wiedervereinigung": "mayflowergmbh/wiedervereinigung",
    "llama-3b": "llama3.2:3b",
}

GEN_OPTS = {
    "temperature": 0,
    "top_p": 1,
    "num_predict": 512,
}

MAX_ARTICLE_CHARS = 1400
TIMEOUT_SECONDS = 120


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate summaries via Ollama.")
    parser.add_argument("--input", default="articles.csv", help="Input CSV with an article column.")
    parser.add_argument("--output", default="generated_summaries.csv", help="Output CSV path.")
    parser.add_argument("--prompt", default="summary_generation_prompt.md", help="Prompt template path.")
    parser.add_argument("--article-column", default="article", help="Article text column name.")
    parser.add_argument(
        "--models",
        nargs="+",
        default=list(MODEL_MAP.keys()),
        choices=sorted(MODEL_MAP.keys()),
        help="Model output columns to generate.",
    )
    parser.add_argument(
        "--ollama-url",
        default=os.getenv("OLLAMA_HOST", "http://localhost:11434"),
        help="Ollama host URL.",
    )
    parser.add_argument("--no-backup", action="store_true", help="Do not backup an existing output file.")
    parser.add_argument("--quiet", action="store_true", help="Do not print each generated summary preview.")
    return parser.parse_args()


def repair_unbalanced_quotes(raw: str) -> str:
    lines = raw.splitlines(keepends=True)
    fixed_lines, buffer, in_quotes = [], [], False

    def process_line(line: str, quoted: bool) -> bool:
        i = 0
        while i < len(line):
            if line[i] == '"':
                if quoted and i + 1 < len(line) and line[i + 1] == '"':
                    i += 2
                    continue
                quoted = not quoted
            i += 1
        return quoted

    for line in lines:
        buffer.append(line)
        in_quotes = process_line(line, in_quotes)
        if not in_quotes:
            fixed_lines.append("".join(buffer))
            buffer = []

    if buffer:
        if in_quotes:
            buffer.append('"\n')
        fixed_lines.append("".join(buffer))

    text = "".join(fixed_lines)
    if not text.endswith("\n"):
        text += "\n"
    return text


def read_csv_robust(path: Path) -> pd.DataFrame:
    try:
        return pd.read_csv(
            path,
            dtype=str,
            keep_default_na=False,
            engine="python",
            encoding="utf-8",
            quoting=csv.QUOTE_MINIMAL,
            quotechar='"',
            escapechar="\\",
        )
    except Exception:
        raw = path.read_text(encoding="utf-8", errors="replace")
        fixed = repair_unbalanced_quotes(raw)
        return pd.read_csv(
            io.StringIO(fixed),
            dtype=str,
            keep_default_na=False,
            engine="python",
            encoding="utf-8",
            quoting=csv.QUOTE_MINIMAL,
            quotechar='"',
            escapechar="\\",
        )


def load_prompt(path: Path) -> str:
    return path.read_text(encoding="utf-8").strip()


def build_prompt(template: str, article: str) -> str:
    article = (article or "").strip()
    if "{{ARTICLE}}" in template:
        return template.replace("{{ARTICLE}}", article)
    if "<<ARTICLE>>" in template:
        return template.replace("<<ARTICLE>>", article)
    return f"{template}\n\n[ARTICLE]\n{article}\n"


def generate_with_ollama(ollama_url: str, model_tag: str, prompt: str) -> str:
    endpoint = f"{ollama_url.rstrip('/')}/api/generate"
    payload = {
        "model": model_tag,
        "prompt": prompt,
        "stream": False,
        "options": GEN_OPTS,
    }
    response = requests.post(endpoint, json=payload, timeout=TIMEOUT_SECONDS)
    response.raise_for_status()
    data = response.json()
    if data.get("error"):
        raise RuntimeError(f"Ollama error for {model_tag}: {data['error']}")
    output = data.get("response", "")
    if not isinstance(output, str):
        raise RuntimeError(f"Malformed Ollama response for {model_tag}: {json.dumps(data)[:500]}")
    return output.strip()


def backup_if_needed(path: Path, enabled: bool) -> None:
    if enabled and path.exists():
        backup = path.with_suffix(path.suffix + ".bak")
        shutil.copyfile(path, backup)
        print(f"Backup saved: {backup}")


def validate_models(models: Iterable[str]) -> List[str]:
    unknown = [model for model in models if model not in MODEL_MAP]
    if unknown:
        raise ValueError(f"Unknown model aliases: {unknown}. Known aliases: {sorted(MODEL_MAP)}")
    return list(models)


def main() -> None:
    args = parse_args()
    base = Path(__file__).resolve().parent
    input_path = Path(args.input)
    output_path = Path(args.output)
    prompt_path = Path(args.prompt)
    if not prompt_path.is_absolute():
        prompt_path = base / prompt_path

    models = validate_models(args.models)
    df = read_csv_robust(input_path)
    if args.article_column not in df.columns:
        raise RuntimeError(f"Input CSV must contain column {args.article_column!r}.")

    for model_alias in models:
        if model_alias not in df.columns:
            df[model_alias] = ""

    template = load_prompt(prompt_path)
    backup_if_needed(output_path, enabled=not args.no_backup)

    print(f"Ollama URL: {args.ollama_url}")
    print(f"Models: {', '.join(models)}")
    print(f"Generation options: {GEN_OPTS}")

    for row_idx, row in df.iterrows():
        article = str(row.get(args.article_column, ""))[:MAX_ARTICLE_CHARS]
        prompt = build_prompt(template, article)

        for model_alias in models:
            model_tag = MODEL_MAP[model_alias]
            summary = generate_with_ollama(args.ollama_url, model_tag, prompt)
            df.at[row_idx, model_alias] = summary

            if not args.quiet:
                label = f"row {row_idx + 1}/{len(df)} | {model_alias} | {model_tag}"
                print("\n" + "-" * 96)
                print(label)
                print("-" * 96)
                print(shorten(summary.replace("\n", " "), width=800, placeholder="...") or "(empty)")

    df.to_csv(output_path, index=False, encoding="utf-8")
    print(f"\nSaved generated summaries to: {output_path}")


if __name__ == "__main__":
    main()
